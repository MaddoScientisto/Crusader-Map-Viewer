function requireDomElement(selector) {
	const element = document.querySelector(selector);
	if (!element) {
		throw new Error(`Renderer controller expected DOM element ${selector}`);
	}
	return element;
}

function optionalDomElement(selector) {
	return document.querySelector(selector);
}

